//! Curiosity engine — gap analysis, wonder queue, and autonomous question generation.
//!
//! The curiosity engine analyzes the brain's episodic history and knowledge graph
//! to identify gaps, thin coverage areas, and missing connections.  It generates
//! `WonderItem` questions that Lu can explore in future interactions.
//!
//! Gap detection strategies:
//!   1. **Thin coverage** — topics appearing in episodes but with few KUs in the graph
//!   2. **Contradictions** — nodes with opposing keywords (not/no vs positive assertions)
//!   3. **Missing connections** — topics that co-occur in episodes but have no bond
//!   4. **Unanswered causals** — causal KUs whose effect-topics have no mechanism KU

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

// ── WonderItem ────────────────────────────────────────────────────────────────

/// A question generated by the curiosity engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WonderItem {
    pub id: String,
    pub question: String,
    /// How the question was generated.
    pub source: WonderSource,
    /// Priority score (0.0–1.0; higher = more interesting).
    pub priority: f32,
    pub created_at: DateTime<Utc>,
    /// Whether this question has been answered / resolved.
    pub resolved: bool,
}

impl WonderItem {
    pub fn new(question: impl Into<String>, source: WonderSource, priority: f32) -> Self {
        WonderItem {
            id: uuid::Uuid::new_v4().to_string(),
            question: question.into(),
            source,
            priority: priority.clamp(0.0, 1.0),
            created_at: Utc::now(),
            resolved: false,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum WonderSource {
    /// Topic mentioned in episodes but has very few KUs.
    ThinCoverage,
    /// Two topics co-occur but share no bond.
    MissingConnection,
    /// A causal KU's effect domain lacks a mechanism explanation.
    UnexplainedCausal,
    /// Two KUs appear to contradict each other.
    PotentialContradiction,
    /// Explicitly queued by the user or another engine component.
    Manual,
    /// Node with only 1 bond — isolated / dead-end knowledge.
    DeadEnd,
    /// Amygdala scar that has never been re-examined after revocation.
    UnresolvedScar,
    /// Topic that consistently returns 0 or very weak recall results.
    RecurringFailure,
}

// ── WonderQueue ───────────────────────────────────────────────────────────────

#[derive(Debug, Default)]
pub struct WonderQueue {
    pub items: Vec<WonderItem>,
    pub max_size: usize,
    pub total_generated: u64,
    pub total_resolved: u64,
}

impl WonderQueue {
    pub fn new(max_size: usize) -> Self {
        WonderQueue {
            items: Vec::new(),
            max_size,
            total_generated: 0,
            total_resolved: 0,
        }
    }

    /// Add a new wonder item, deduplicating by question text and enforcing max_size.
    pub fn push(&mut self, item: WonderItem) {
        // Deduplicate: skip if a very similar question already exists.
        let q_lower = item.question.to_lowercase();
        if self.items.iter().any(|i| {
            let existing = i.question.to_lowercase();
            similarity_score(&existing, &q_lower) > 0.8
        }) {
            return;
        }

        if self.items.len() >= self.max_size {
            // Evict the lowest-priority resolved item, or the lowest-priority unresolved.
            let evict_idx = self
                .items
                .iter()
                .enumerate()
                .filter(|(_, i)| i.resolved)
                .min_by(|(_, a), (_, b)| a.priority.partial_cmp(&b.priority).unwrap_or(std::cmp::Ordering::Equal))
                .map(|(i, _)| i)
                .or_else(|| {
                    self.items
                        .iter()
                        .enumerate()
                        .min_by(|(_, a), (_, b)| a.priority.partial_cmp(&b.priority).unwrap_or(std::cmp::Ordering::Equal))
                        .map(|(i, _)| i)
                });
            if let Some(idx) = evict_idx {
                self.items.remove(idx);
            }
        }

        self.total_generated += 1;
        self.items.push(item);
    }

    /// Mark a wonder item as resolved by id.
    pub fn resolve(&mut self, id: &str) -> bool {
        if let Some(item) = self.items.iter_mut().find(|i| i.id == id) {
            item.resolved = true;
            self.total_resolved += 1;
            true
        } else {
            false
        }
    }

    /// Return unresolved items sorted by priority descending.
    pub fn pending(&self) -> Vec<&WonderItem> {
        let mut v: Vec<&WonderItem> = self.items.iter().filter(|i| !i.resolved).collect();
        v.sort_by(|a, b| b.priority.partial_cmp(&a.priority).unwrap_or(std::cmp::Ordering::Equal));
        v
    }

    pub fn pending_count(&self) -> usize {
        self.items.iter().filter(|i| !i.resolved).count()
    }
}

// ── CuriosityEngine ───────────────────────────────────────────────────────────

#[derive(Debug, Default)]
pub struct CuriosityEngine {
    pub wonder_queue: WonderQueue,
    pub analysis_count: u64,
    /// Topics with consistently weak recall — fed into analyze_extended.
    pub weak_query_topics: Vec<String>,
}

impl CuriosityEngine {
    pub fn new() -> Self {
        CuriosityEngine {
            wonder_queue: WonderQueue::new(256),
            analysis_count: 0,
            weak_query_topics: Vec::new(),
        }
    }

    /// Record a topic that returned weak recall results.
    ///
    /// Adds the topic to `weak_query_topics` (used by `analyze()`) and
    /// immediately pushes a RecurringFailure wonder item to the queue.
    pub fn record_weak_query(&mut self, topic: &str) {
        if topic.is_empty() {
            return;
        }
        let topic_s = topic.to_string();
        if !self.weak_query_topics.contains(&topic_s) {
            if self.weak_query_topics.len() >= 100 {
                self.weak_query_topics.remove(0);
            }
            self.weak_query_topics.push(topic_s);
        }
        let q = format!(
            "Queries about '{}' consistently return weak results. \
             What should I know about this topic?",
            &topic[..60.min(topic.len())]
        );
        self.wonder_queue.push(WonderItem::new(q, WonderSource::RecurringFailure, 0.65));
    }

    /// Analyse recent episodes and graph state to find knowledge gaps.
    ///
    /// `episode_descriptions` — recent episode description strings.
    /// `node_labels`          — (label, ku_kind_str) pairs for all active nodes.
    /// `bond_pairs`           — (source_label, target_label) for all active bonds.
    /// `scar_labels`          — labels of amygdala scars (for UnresolvedScar detection).
    /// `weak_query_topics`    — topics with consistently poor recall (for RecurringFailure).
    ///
    /// Returns the number of new wonder items generated.
    pub fn analyze(
        &mut self,
        episode_descriptions: &[String],
        node_labels: &[(String, String)],
        bond_pairs: &[(String, String)],
    ) -> usize {
        self.analyze_extended(episode_descriptions, node_labels, bond_pairs, &[], &[])
    }

    /// Extended analyze with scar and weak-topic awareness.
    pub fn analyze_extended(
        &mut self,
        episode_descriptions: &[String],
        node_labels: &[(String, String)],
        bond_pairs: &[(String, String)],
        scar_labels: &[String],
        weak_query_topics: &[String],
    ) -> usize {
        self.analysis_count += 1;
        let before = self.wonder_queue.total_generated;

        // ── Strategy 1: Thin coverage ─────────────────────────────────────────
        // Count how many nodes mention each topic from episodes.
        let topics = extract_topics_from_episodes(episode_descriptions);
        for topic in &topics {
            let coverage = node_labels.iter().filter(|(lbl, _)| {
                lbl.to_lowercase().contains(&topic.to_lowercase())
            }).count();

            if coverage < 2 && !topic.is_empty() {
                let q = format!("What is {topic}? I've seen it mentioned but don't have deep knowledge about it.");
                self.wonder_queue.push(WonderItem::new(q, WonderSource::ThinCoverage, 0.6));
            }
        }

        // ── Strategy 2: Missing connections ─────────────────────���─────────────
        // Topics that co-appear in the same episode but have no bond between them.
        let bond_set: std::collections::HashSet<(String, String)> = bond_pairs
            .iter()
            .flat_map(|(a, b)| {
                let al = a.to_lowercase();
                let bl = b.to_lowercase();
                vec![(al.clone(), bl.clone()), (bl, al)]
            })
            .collect();

        for ep in episode_descriptions {
            let ep_topics = extract_topics_from_text(ep);
            for i in 0..ep_topics.len() {
                for j in (i + 1)..ep_topics.len() {
                    let t1 = &ep_topics[i];
                    let t2 = &ep_topics[j];
                    if !bond_set.contains(&(t1.clone(), t2.clone())) {
                        let q = format!("How does {t1} relate to {t2}? They appear together but I haven't connected them.");
                        self.wonder_queue.push(WonderItem::new(
                            q,
                            WonderSource::MissingConnection,
                            0.5,
                        ));
                    }
                }
            }
        }

        // ── Strategy 3: Unexplained causals ───────────────────────────────────
        // Any causal KU whose effect topic has no mechanism or definition node.
        let causal_nodes: Vec<&str> = node_labels
            .iter()
            .filter(|(_, kind)| kind == "causal")
            .map(|(lbl, _)| lbl.as_str())
            .collect();

        for causal_lbl in causal_nodes {
            // Rough heuristic: extract "causes" or "leads to" target.
            if let Some(effect) = extract_effect_from_causal(causal_lbl) {
                let has_mechanism = node_labels.iter().any(|(lbl, kind)| {
                    lbl.to_lowercase().contains(&effect.to_lowercase())
                        && (kind == "mechanism" || kind == "definition")
                });
                if !has_mechanism {
                    let q = format!("How does {effect} work? I know it's caused by something but I don't have a mechanism.");
                    self.wonder_queue.push(WonderItem::new(
                        q,
                        WonderSource::UnexplainedCausal,
                        0.7,
                    ));
                }
            }
        }

        // ── Strategy 4: Potential contradictions ──────────────────────────────
        // Nodes with similar subjects but opposing sentiment words.
        detect_contradictions(node_labels, &mut self.wonder_queue);

        // ── Strategy 5: Dead ends ─────────────────────────────────────────────
        // Nodes mentioned only once in bond_pairs (degree 1 = isolated).
        let mut bond_degree: std::collections::HashMap<String, usize> =
            std::collections::HashMap::new();
        for (a, b) in bond_pairs {
            *bond_degree.entry(a.to_lowercase()).or_insert(0) += 1;
            *bond_degree.entry(b.to_lowercase()).or_insert(0) += 1;
        }
        for (label, _kind) in node_labels {
            let deg = bond_degree.get(&label.to_lowercase()).copied().unwrap_or(0);
            if deg == 1 {
                let short = &label[..50.min(label.len())];
                let q = format!("'{}' seems isolated — what else connects to it?", short);
                self.wonder_queue.push(WonderItem::new(q, WonderSource::DeadEnd, 0.45));
            }
        }

        // ── Strategy 6: Unresolved scars ──────────────────────────────────────
        for scar_label in scar_labels {
            if !scar_label.is_empty() {
                let q = format!(
                    "I previously revoked knowledge about '{}'. \
                     Should I reconsider this topic?",
                    &scar_label[..60.min(scar_label.len())]
                );
                self.wonder_queue.push(WonderItem::new(
                    q, WonderSource::UnresolvedScar, 0.55,
                ));
            }
        }

        // ── Strategy 7: Recurring failures ───────────────────────────────────
        for topic in weak_query_topics {
            if !topic.is_empty() {
                let q = format!(
                    "Queries about '{}' consistently return weak results. \
                     What should I know about this topic?",
                    &topic[..60.min(topic.len())]
                );
                self.wonder_queue.push(WonderItem::new(
                    q, WonderSource::RecurringFailure, 0.65,
                ));
            }
        }

        (self.wonder_queue.total_generated - before) as usize
    }


    /// Generate a fixed set of wonder items from graph introspection alone
    /// (no episodes required).  Useful when the episode history is empty.
    pub fn generate_from_graph(
        &mut self,
        node_labels: &[(String, String)],
    ) -> usize {
        let before = self.wonder_queue.total_generated;

        // Find singleton topics (nodes with no bonds to the same subject).
        let kind_counts: std::collections::HashMap<String, usize> =
            node_labels.iter().fold(std::collections::HashMap::new(), |mut m, (_, k)| {
                *m.entry(k.clone()).or_insert(0) += 1;
                m
            });

        // If there are many Raw KUs but few Definition KUs, suggest improvement.
        let raw_count = kind_counts.get("raw").copied().unwrap_or(0);
        let def_count  = kind_counts.get("definition").copied().unwrap_or(0);
        if raw_count > 5 && def_count < raw_count / 3 {
            self.wonder_queue.push(WonderItem::new(
                "Many of my nodes are untyped. What topics should I define more precisely?",
                WonderSource::ThinCoverage,
                0.4,
            ));
        }

        (self.wonder_queue.total_generated - before) as usize
    }
}

// ── Helpers ───────────────────────────────────────────────────────────────────

/// Extract meaningful topic words from episode description strings.
fn extract_topics_from_episodes(episodes: &[String]) -> Vec<String> {
    let mut topics = std::collections::HashSet::new();
    for ep in episodes {
        for t in extract_topics_from_text(ep) {
            topics.insert(t);
        }
    }
    topics.into_iter().collect()
}

/// Extract capitalised or quoted words as potential topics.
fn extract_topics_from_text(text: &str) -> Vec<String> {
    const STOP: &[&str] = &[
        "the", "a", "an", "and", "or", "but", "is", "are", "was", "were",
        "in", "on", "at", "to", "for", "of", "with", "that", "this",
        "from", "by", "as", "be", "it", "its", "has", "have", "had",
        "will", "would", "can", "could", "may", "might", "shall", "should",
        "not", "no", "nor", "yet", "so",
        // Episode meta-words from Brain::respond() format strings.
        "words", "recalled", "sub-questions", "thinking", "chain",
    ];

    text.split(|c: char| !c.is_alphanumeric() && c != '_')
        .map(|w| w.trim().to_lowercase())
        .filter(|w| w.len() >= 4 && !STOP.contains(&w.as_str()))
        .collect()
}

/// Very rough: try to extract the "effect" from a causal label like
/// "heat causes expansion" → "expansion".
fn extract_effect_from_causal(label: &str) -> Option<String> {
    let lower = label.to_lowercase();
    for marker in &["causes", "leads to", "results in", "produces"] {
        if let Some(pos) = lower.find(marker) {
            let after = label[pos + marker.len()..].trim();
            if !after.is_empty() {
                let word = after.split_whitespace().next()?;
                return Some(word.to_string());
            }
        }
    }
    None
}

/// Detect potential contradictions: pairs of nodes whose labels share a
/// subject but one uses negation keywords the other doesn't.
fn detect_contradictions(
    node_labels: &[(String, String)],
    queue: &mut WonderQueue,
) {
    let negation = ["not", "never", "no ", "cannot", "can't", "doesn't", "isn't"];

    // Cap to 200 items max — O(n²) loop; 2000 items = ~2M iterations which
    // causes stack exhaustion and crashes the brain worker on query 20+.
    let cap = node_labels.len().min(200);

    for i in 0..cap {
        for j in (i + 1)..cap {
            let (a, _) = &node_labels[i];
            let (b, _) = &node_labels[j];
            let al = a.to_lowercase();
            let bl = b.to_lowercase();

            let a_has_neg = negation.iter().any(|n| al.contains(n));
            let b_has_neg = negation.iter().any(|n| bl.contains(n));

            // One has negation, the other doesn't — AND they share significant words.
            if a_has_neg != b_has_neg {
                let sim = similarity_score(&al, &bl);
                if sim > 0.45 {
                    let q = format!(
                        "I have conflicting information — one source says '{}' and another says '{}'. Which is correct?",
                        truncate(a, 60), truncate(b, 60)
                    );
                    queue.push(WonderItem::new(q, WonderSource::PotentialContradiction, 0.8));
                }
            }
        }
    }
}

/// Compute a simple Jaccard similarity over word sets.
fn similarity_score(a: &str, b: &str) -> f32 {
    let a_words: std::collections::HashSet<&str> = a.split_whitespace().collect();
    let b_words: std::collections::HashSet<&str> = b.split_whitespace().collect();
    let intersection = a_words.intersection(&b_words).count();
    let union = a_words.union(&b_words).count();
    if union == 0 {
        return 0.0;
    }
    intersection as f32 / union as f32
}

fn truncate(s: &str, max: usize) -> &str {
    if s.len() <= max {
        s
    } else {
        &s[..max]
    }
}
